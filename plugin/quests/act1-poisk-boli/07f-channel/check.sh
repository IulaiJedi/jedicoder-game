#!/usr/bin/env bash
# Акт 1, квест 07f (трек Основатель): ровно один канал доставки.
# Распыление на пять каналов — самая частая ошибка этого шага, и Акт 5
# опирается на этот выбор.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/md.sh"

FILE=research/CHANNEL.md

jc_init "act1/07f-channel"

jc_check channel_exists "research/CHANNEL.md есть и непустой" \
  "Создай research/CHANNEL.md и назови один канал, через который придут люди" \
  test -s "$FILE"
# Якорь в конце обязателен: без него «## Каналы, которые пробовал» сошёл бы
# за секцию канала. Заголовок документа в тон квесту («# Канал» строкой выше
# «## Канал») здесь не мешает: jc_section судит заголовок уровня ≥2, то есть
# раздел. Локального лекарства (лишней решётки в паттерне) больше нет —
# правило общее для всех квестов и живёт в одном месте.
jc_check channel_one "Под «## Канал» ровно одна строка" \
  "Оставь ровно один канал одной строкой. Пять каналов — это ноль каналов" \
  jc_section_one_line "$FILE" '[Кк]анал[[:space:]]*$'
jc_check channel_why "Раздел «## Почему он» заполнен" \
  "Добавь раздел ## Почему он — почему люди придут именно оттуда" \
  jc_section_words "$FILE" '[Пп]очему он' 8
jc_finish
