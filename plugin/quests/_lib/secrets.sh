# shellcheck shell=bash
# Паттерны строк, похожих на секреты. Общие для актов: Акт 2 ловит утечку
# до пуша (05-env-guard), Акт 4 — перед выходом на GitHub (03m-secrets).
#
# Граница слова у sk- набрана (^|[^A-Za-z0-9]), а не \b: \b — GNU-
# расширение, BSD grep из macOS его не обещает. Голого sk- без границы и
# длины быть не должно: он матчит «risk-assessment» — ложный провал на
# невинном тексте.
#
# Формы: sk-… (устаревший OpenAI-стиль), sk-ant-… (Anthropic), sk-proj-…
# (новый OpenAI), ghp_… (классические токены GitHub), github_pat_…
# (fine-grained), NNNNNNNN:AA… (боты Telegram).
#
# Второй заход (2026-09-10, прогон игры по CLI): три самых частых утечки
# уходили мимо, и все три — у падавана, который довёл продукт до денег.
#
# * `sk_live_…`, `sk_test_…`, `rk_live_…` — Stripe. Подчёркивания, а не
#   дефисы: старый класс их не видел вовсе, а именно этот ключ и стоит в
#   коде того, кто первым принял оплату. `pk_…` намеренно НЕ здесь: это
#   публикуемый ключ, его место как раз в коде страницы, и пометить его
#   утечкой значило бы научить неправде.
# * `AKIA…` — ключ доступа AWS. Ровно двадцать знаков, только заглавные и
#   цифры; хвост-секрет рядом ловить не пытаемся — он выглядит как обычная
#   строка base64, и на нём ложных срабатываний было бы больше, чем пользы.
# * `xoxb-`, `xoxp-`, `xapp-` — токены Slack.

# Ключ бота Telegram: номер бота, двоеточие, хвост с `AA` в начале. Один
# образец на всю игру: им ищут утечку (JC_SECRET_RE ниже) и ключ бота в
# `.env` квеста «Работает» Акта 4.
JC_TELEGRAM_TOKEN_RE='[0-9]{8,10}:AA[A-Za-z0-9_-]{30,}'

JC_SECRET_RE='((^|[^A-Za-z0-9])sk-[A-Za-z0-9]{16,}|(^|[^A-Za-z0-9])sk-(ant|proj)-[A-Za-z0-9_-]{16,}|(^|[^A-Za-z0-9])(sk|rk)_(live|test)_[A-Za-z0-9]{16,}|ghp_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{22,}|(^|[^A-Za-z0-9])AKIA[A-Z0-9]{16}|(^|[^A-Za-z0-9])xox[bpasr]-[A-Za-z0-9-]{10,}|'"$JC_TELEGRAM_TOKEN_RE"')'
