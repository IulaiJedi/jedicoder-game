# shellcheck shell=bash
# Предикаты разбора markdown для проверок Акта 1.
#
# emit.sh отвечает за контракт JSON и exit-кодов; здесь только разбор текста.
# Все предикаты возвращают 0 (условие выполнено) или 1 и не пишут в stdout:
# по контракту check.sh в stdout можно только JSON.
#
# ERE заголовка матчится против текста ПОСЛЕ решёток и пробелов, по префиксу:
# '[Бб]оль' найдёт «## Боль — что бесит». Где нужна точность, якори сам:
# '[Кк]анал[[:space:]]*$'.
#
# Регистр первой буквы задаётся классом, а не grep -i и не tolower(): ни один
# из них не складывает кириллицу предсказуемо во всех локалях.
# awk — только POSIX: IGNORECASE есть в gawk, но не в mawk, который стоит по
# умолчанию в WSL Ubuntu, и там он молча не сработает.
#
# UTF-8-локаль, без которой кириллица не матчится вовсе, подбирает emit.sh:
# это свойство всей проверки, а не разбора markdown, и emit.sh сорсят все
# check.sh всех актов. Здесь — только страховка на случай, когда md.sh
# сорсят отдельно, без emit.sh (так делают тесты предикатов): иначе
# предикаты остались бы в унаследованной локали и не нашли бы ни одного
# русского заголовка.
#
# Направление зависимости именно такое: md.sh — надстройка над emit.sh
# (markdown-квесты сорсят оба, обратное невозможно). Зависимость в другую
# сторону затащила бы разбор markdown в каждую проверку игры.
#
# Сорсится безусловно: от повторного прогона (он обнулил бы собранные строки
# отчёта JC_ROWS и второй раз гонял бы locale -a) emit.sh защищается сам.
# Проверять здесь «а не загружен ли уже» — значит защищать только тот порядок
# source, который автор этой строки держал в голове.
# shellcheck source=./emit.sh
source "$(dirname "${BASH_SOURCE[0]}")/emit.sh"

# Тело секции, заголовок которой стоит на строке <номер>: всё до следующего
# заголовка любого уровня или до конца файла.
_jc_section_at() {
  awk -v start="$2" '
    NR == start { inside = 1; next }
    inside && /^#+[[:space:]]/ { exit }
    inside { print }
  ' "$1"
}

# jc_section <файл> <ERE заголовка> — напечатать строки секции
#
# Совпадений по префиксу бывает несколько, и первое по номеру строки — почти
# всегда не то: падаван называет файл в тон квесту, и заголовок документа
# («# Боль», «# CAC, LTV и стоимость токенов») оказывается написан теми же
# словами, что искомая секция, только строкой выше. Проверка судила его — и
# валила написанное, а подсказка звала добавить раздел, который уже есть.
# Тупик: правило, по которому судят, невидимо тому, кого судят.
#
# Правило: судим РАЗДЕЛ, то есть заголовок уровня ≥2. Ровно его называет
# каждая подсказка («Добавь раздел ## Боль») и ровно его диктует скилл акта,
# так что правило видно тому, кого по нему судят. Заголовок первого уровня
# рассматривается только если разделов не нашлось вовсе: тогда падаван
# оформил документ одними решётками, и это рабочий путь, отбирать его не за
# что. Иначе говоря — обобщение того самого локального лекарства, которое
# жило в 07f-channel («минимум две решётки»), плюс откат, из-за отсутствия
# которого лекарство и нельзя было обобщить как есть.
#
# Почему не «первое НЕПУСТОЕ совпадение»: рассуждение «правка монотонна,
# провал может стать проходом, а проход провалом — нет» молча предполагает
# неизменный паттерн и не держится для jc_section_one_line, где «ровно одна
# строка» не монотонна в ту же сторону, что счётчики слов. На файле, где под
# «# Канал» строка вступления, а под «## Канал» три канала, вступление
# выигрывало — и квест, существующий ради правила «пять каналов — это ноль
# каналов», засчитывал три. Кто победит, решала пустота соседнего заголовка,
# то есть удача разметки, а не exit-код по написанному.
#
# Тело секции не разглядывается вовсе — только уровень заголовка. Это заодно
# снимает предел по размеру: проба тела шла конвейером `printf | grep -q`,
# а под `set -o pipefail` (его ставит каждый check.sh) ранний выход grep даёт
# писателю EPIPE, SIGPIPE и 141 — и полностью написанная секция считалась
# пустой. Предел был не фиксированный, а гонка на буфере трубы: 64 КБ
# проваливались в 19 прогонах из 20, 32 КБ — в 3 из 20.
#
# Кириллицу матчит grep, не awk: у mawk (дефолтный awk на WSL Ubuntu)
# собственный движок регэкспов ломается именно на связке «якорь + класс
# из нескольких кириллических букв + буквы следом» — например, '^[Бб]оль'
# не находит «Боль», хотя '[Бб]оль' без якоря находит. Проверено напрямую:
# так же собранный паттерн через grep matches, через mawk — нет, в любой
# локали. Поэтому кириллицу ищет grep (находит номера строк заголовков),
# а awk работает только с номерами строк и ASCII-заголовками — сюда эта
# болезнь mawk не дотягивается.
jc_section() {
  local file=$1 pattern=$2 starts
  [ -f "$file" ] || return 1
  starts=$(grep -nE "^#{2,}[[:space:]]*$pattern" "$file" | cut -d: -f1)
  [ -n "$starts" ] || starts=$(grep -nE "^#+[[:space:]]*$pattern" "$file" | cut -d: -f1)
  [ -n "$starts" ] || return 0
  # Первая строка списка, срезанная раскрытием параметра, а не `head -1`:
  # head закрыл бы трубу на первой строке, и под pipefail это тот же EPIPE,
  # от которого избавлена сама секция. Здесь grep и cut дочитывают до конца.
  _jc_section_at "$file" "${starts%%$'\n'*}"
}

# jc_has_heading <файл> <ERE заголовка>
jc_has_heading() {
  local file=$1 pattern=$2
  [ -f "$file" ] || return 1
  grep -qE "^#+[[:space:]]*$pattern" "$file"
}

# Слова секции за вычетом слов-заглушек. Заглушка вычёркивается целой
# строкой: «TODO» отдельной строкой — пусто, «TODO: разобраться с ЦА» — нет.
_jc_meaningful() {
  jc_section "$1" "$2" \
    | grep -vxE '[[:space:]]*(TODO|TBD|XXX|FIXME|todo|tbd|-|--|—|\.\.\.|…|\?+)[[:space:]]*'
}

# jc_section_words <файл> <ERE заголовка> <минимум слов>
jc_section_words() {
  local count
  count=$(_jc_meaningful "$1" "$2" | wc -w)
  [ "$count" -ge "$3" ]
}

# jc_section_matches <файл> <ERE заголовка> <ERE содержимого>
#
# Читатель обязан дочитать секцию до конца, поэтому `grep -cE` со сбросом
# счётчика в /dev/null, а не `grep -qE`: `-q` выходит на первом совпадении,
# писатель упирается в буфер трубы, получает EPIPE и SIGPIPE, и под
# `set -o pipefail` (его ставит каждый check.sh) конвейер отдаёт 141 — то
# есть отказ. Секция «## CAC» на 200 КБ проваливала 06f-unit в 10 прогонах
# из 10. Код возврата у -c тот же, что у -q: 0, когда совпадение нашлось.
# Сброс в /dev/null обязателен — предикаты не пишут в stdout, там только JSON.
jc_section_matches() {
  jc_section "$1" "$2" | grep -cE "$3" >/dev/null
}

# jc_section_one_line <файл> <ERE заголовка> — ровно одна непустая строка
jc_section_one_line() {
  local count
  count=$(jc_section "$1" "$2" | grep -c '[^[:space:]]')
  [ "$count" -eq 1 ]
}

# jc_file_words <файл> <минимум слов>
jc_file_words() {
  local count
  [ -f "$1" ] || return 1
  count=$(wc -w < "$1")
  [ "$count" -ge "$2" ]
}

# jc_min_matches <минимум> <ERE> <файл>
jc_min_matches() {
  local count
  [ -f "$3" ] || return 1
  count=$(grep -oE "$2" "$3" | wc -l)
  [ "$count" -ge "$1" ]
}

# jc_min_urls <минимум> <файл> — считаются РАЗНЫЕ ссылки: три копии одной
# ссылки не три конкурента.
#
# Класс исключений: ']' первым символом после '^' — литерал по правилу POSIX,
# а следом обязателен СВОЙ закрывающий ']' у именованного класса [:space:] —
# без него GNU grep не находит конец класса и вся регулярка не компилируется
# («Unmatched [, [^, [:, [., or [=»), grep падает молча (пустой stdout), и
# предикат отказывает всегда, при любом входе.
jc_min_urls() {
  local count
  [ -f "$2" ] || return 1
  count=$(grep -oE 'https?://[^][:space:]>)"]+' "$2" | sort -u | wc -l)
  [ "$count" -ge "$1" ]
}
