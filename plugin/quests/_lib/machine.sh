# shellcheck shell=bash
# Машина игрока вне папки проекта: свои скиллы и хук в настройках Claude Code.
#
# Квесты Акта 3 «Свой скилл» и «Хук» судят то, что Claude сделал по словам
# человека. Лежит это в двух местах: в папке проекта (`.claude/…`) и в
# домашней папке (`~/.claude/…`). Домашняя папка берётся из HOME и только из
# неё: тесты подменяют HOME песочной папкой, и настоящий `~/.claude` суит не
# читает.
#
# Только чтение. Нет файла или папки — это «не сделано», честный провал
# с подсказкой. Есть, но не читается, — «не смог проверить» (jc_bail): такая
# попытка человеку не засчитывается.
#
# Готовых скиллов из сети игра не ставит и не ищет (решение оператора
# 2026-10-14, #116): списка плагинов Claude Code эти проверки не читают.
#
# Сорсить после emit.sh: здесь зовётся jc_bail.

# jc_machine_guard — домашняя папка названа и существует.
jc_machine_guard() {
  [ -n "${HOME:-}" ] && [ -d "$HOME" ] \
    || jc_bail "не нашёл домашнюю папку этого компьютера — проверить нечем"
}

# Готовые скиллы, которые игра называет примерами в квесте «Где брать»:
# скилл про вид страниц и набор автора игры. Игра их не ставит, но человек
# мог поставить их сам — квест «Свой скилл» их своими не считает. Перечень
# один: новому примеру игры — имя сюда.
JC_KNOWN_SKILLS="impeccable sdd"

# Разбор своего скилла и настроек Claude Code — один на проверку и на хук
# следов: `lib/jedicoder/machine.py`. Здесь только вызов.
_JC_MACHINE_PY="$(dirname "${BASH_SOURCE[0]}")/../../lib/jedicoder/machine.py"

_jc_machine_py() {
  command -v python3 >/dev/null 2>&1 \
    || jc_bail "не найден python3 — без него настройки Claude Code не прочитать"
  [ -f "$_JC_MACHINE_PY" ] \
    || jc_bail "игра установлена не целиком: нет файла разбора настроек"
  python3 "$_JC_MACHINE_PY" "$@"
}

# jc_own_skill [вход в акт] — исход поиска своего скилла словом: none,
# no-description, no-body, ok (что они значат — в machine.py). Смотрит папку
# проекта, а личные скиллы — только изменённые не раньше входа в акт (секунды
# эпохи; пусто — личные не смотрятся). Зовётся из папки проекта.
#
# Зовут её подстановкой `$(…)`: jc_bail внутри гасит только подстановку,
# поэтому вызывающий сам выходит по её коду — `VERDICT=$(jc_own_skill …) ||
# exit 2`.
jc_own_skill() {
  local verdict code
  # shellcheck disable=SC2086 — перечень имён нарочно делится по пробелам
  verdict=$(_jc_machine_py own-skill "$PWD" "$HOME" "${1:-}" $JC_KNOWN_SKILLS)
  code=$?
  # Код 2 — jc_bail внутри подстановки: причина уже названа, второй не надо.
  [ "$code" -ne 2 ] || exit 2
  [ "$code" -eq 0 ] \
    || jc_bail "не могу заглянуть в папку со скиллами — попроси Claude посмотреть, что с ней"
  printf '%s\n' "$verdict"
}

# jc_prompt_hook_recorded — в настройках проекта или пользователя записан хук
# на запрос (событие UserPromptSubmit). Файла настроек нет — не записан.
# Файл есть, но это не JSON, — jc_bail.
jc_prompt_hook_recorded() {
  local code
  _jc_machine_py prompt-hook "$PWD" "$HOME"
  code=$?
  [ "$code" -le 1 ] \
    || jc_bail "не могу прочитать настройки Claude Code — попроси Claude посмотреть, что с файлом настроек"
  return "$code"
}
