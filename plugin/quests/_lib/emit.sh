# shellcheck shell=bash
# Хелпер для check.sh: собрать JSON-отчёт и вернуть правильный exit-код.
#
# Контракт check.sh: в stdout только JSON, диагностика в stderr,
# exit 0 — квест закрыт, 1 — не закрыт, 2 — не смогли проверить.
# Скрипт НИКОГДА не меняет проект падавана.
#
# Использование:
#   source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"
#   jc_init "act2/04-git-init"
#   jc_check repo_exists "Репозиторий инициализирован" "Запусти git init" \
#            git rev-parse --git-dir
#   jc_finish

# Повторный source — пустышка, и охраняет это сам emit.sh, а не тот, кто его
# сорсит. Второй прогон обнулил бы JC_ROWS: уже собранные результаты проверок
# молча исчезли бы из JSON, а падаван увидел бы отчёт без половины строк.
# Раньше guard стоял в md.sh и защищал только один порядок — «emit.sh, потом
# md.sh». Обратный («md.sh, потом emit.sh») пробивал его насквозь: md.sh сорсил
# emit.sh сам, а следующая строка сорсила его второй раз. Сейчас все тринадцать
# check.sh пишут emit.sh первым, так что это была ловушка для следующего автора
# квеста, а не живой отказ, — но цена ей одна строка, а цена промаха тихая.
if declare -F jc_finish >/dev/null 2>&1; then
  return 0
fi

# Локаль падавана — лотерея: у свежего WSL Ubuntu она нередко вообще не
# задана (LANG пуст), а LC_ALL=C приезжает из чужих скриптов и CI. Без
# UTF-8-локали grep и awk режут «Б»/«б» на байты вместо букв, и ни класс
# [Бб], ни grep -i не находят то, что реально есть в файле. Поэтому локаль
# фиксируем явно, а не полагаемся на окружение вызывающего.
#
# Живёт это в emit.sh, а не в разборе markdown, потому что локаль — свойство
# всей проверки, а не одного её приёма: emit.sh сорсят ВСЕ check.sh, значит
# защита достаётся и Акту 2, который md.sh не сорсит, и будущим актам — по
# умолчанию, а не по памяти автора. До переезда Акт 2 вставал намертво на
# 01-recipe и 03-db-schema при LC_ALL=C, а с пустым LANG спасала случайность:
# CPython по PEP 538 подставляет детям LC_CTYPE=C.UTF-8.
#
# Именем локаль задавать нельзя: падаван бывает на macOS (см. паспорт, поле
# os: win_wsl | mac | linux), а там локали C.UTF-8 не существует. Присваивание
# несуществующего имени bash проглатывает молча, grep/awk откатываются на C,
# и кириллица снова не матчится — ровно то, от чего эта строка должна была
# защищать, просто тихо. Поэтому берём не имя, а то, что реально стоит на
# машине: locale -a — POSIX, есть везде, где есть bash. Нет UTF-8-локали
# вовсе — не трогаем LC_ALL: сломанная назначенная локаль хуже унаследованной
# непредсказуемой (унаследованная хотя бы могла быть настроена правильно).
_jc_locales=$(locale -a 2>/dev/null)
# Сначала нейтральная (без своего языка/региона — не тащит региональные
# особенности формата): C.UTF-8/C.utf8 у glibc (Linux, WSL), голое UTF-8 у
# macOS. Не нашлась — берём любую UTF-8-локаль, какая есть: региональная
# лучше, чем никакая.
_jc_utf8_locale=$(printf '%s\n' "$_jc_locales" | grep -iE '^(C\.utf-?8|UTF-?8)$' | head -1)
[ -n "$_jc_utf8_locale" ] || _jc_utf8_locale=$(printf '%s\n' "$_jc_locales" | grep -iE 'utf-?8' | head -1)
[ -n "$_jc_utf8_locale" ] && export LC_ALL="$_jc_utf8_locale"
unset _jc_locales _jc_utf8_locale

JC_QUEST=""
JC_ROWS=()
JC_OK=1

jc_init() {
  JC_QUEST="$1"
  JC_ROWS=()
  JC_OK=1
}

jc_escape() {
  local value=$1
  value=${value//\\/\\\\}
  value=${value//\"/\\\"}
  value=${value//$'\n'/ }
  value=${value//$'\t'/ }
  printf '%s' "$value"
}

# jc_check <id> <label> <hint> <команда...>
#
# stdout проверяемой команды глушится (в stdout можно только JSON), а stderr
# пропускается наружу: по контракту диагностика идёт в stderr, и без неё
# отсутствие бинарника неотличимо от невыполненного условия.
jc_check() {
  _jc_row "" "$@"
}

# jc_check_quiet <id> <label> <hint> <команда...>
#
# Строка-сторож: судит так же, как jc_check, и квест без неё не закроется, но
# пока она сошлась, человеку её не показывают (поле "quiet" в JSON). Нужна
# проверкам, которые стерегут то, о чём человеку рано слышать: квест
# «Сохранение» Акта 1 следит за `.env` и ключами в первый же вечер, когда
# паролей у новичка ещё нет (#87). Не сошлась — печатается, как любая другая.
jc_check_quiet() {
  _jc_row ',"quiet":true' "$@"
}

_jc_row() {
  local extra=$1 id=$2 label=$3 hint=$4
  shift 4
  local ok="true"
  if ! "$@" >/dev/null; then
    ok="false"
    JC_OK=0
  fi
  JC_ROWS+=("$(printf '{"id":"%s","ok":%s,"label":"%s","hint":"%s"%s}' \
    "$(jc_escape "$id")" "$ok" "$(jc_escape "$label")" "$(jc_escape "$hint")" \
    "$extra")")
}

jc_finish() {
  local ok_json="false"
  [ "$JC_OK" -eq 1 ] && ok_json="true"
  local joined
  joined=$(IFS=,; printf '%s' "${JC_ROWS[*]-}")
  printf '{"quest":"%s","ok":%s,"checks":[%s]}\n' \
    "$(jc_escape "$JC_QUEST")" "$ok_json" "$joined"
  [ "$JC_OK" -eq 1 ] && exit 0
  exit 1
}

# jc_bail <причина> — не смогли проверить, попытка не засчитывается
jc_bail() {
  printf '%s\n' "$1" >&2
  exit 2
}
