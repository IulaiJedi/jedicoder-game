#!/usr/bin/env bash
# Акт 2, квест 04: разговор начат заново — командой `/clear` — уже после
# того, как память проекта записана.
#
# До этой проверки движок ждёт слов человека (acts.WORDS_FIRST): он спросил
# Claude про проект в новом разговоре и рассказал, что услышал. Сам `/clear`
# записывает хук игровой сессии (след, ADR-0020 в репозитории сайта); сюда
# след приходит переменной JEDICODER_TRACE_CLEARED=yes. «После памяти
# проекта» решает тот, кто пишет и передаёт след: сохранение проверка не
# читает.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"

cleared() { [ "${JEDICODER_TRACE_CLEARED:-}" = "yes" ]; }

jc_init "act2/04-clear"
jc_check cleared "Ты начал новый разговор после записи памяти проекта" \
  "Игра не видела нового разговора. Запиши передачу и набери /clear. Потом спроси Claude, на чём остановились." \
  cleared
jc_finish
