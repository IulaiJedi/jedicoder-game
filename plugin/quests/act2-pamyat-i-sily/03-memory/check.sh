#!/usr/bin/env bash
# Акт 2, квест 03: у проекта есть память — файл CLAUDE.md, который Claude
# читает в начале каждого разговора. В нём четыре раздела, и ни один не пуст:
# что это за проект, как его открыть, чего не трогать и правила работы.
# Четвёртый раздел судится только по наличию и непустоте: правило человек
# называет своё, обычное — «после важных изменений сохраняй сам».
#
# Файл диктует человек, пишет Claude. Claude Code читает его из двух мест —
# `CLAUDE.md` в корне проекта и `.claude/CLAUDE.md`; принимаются оба. Судится
# первый из них, в котором что-то написано: пустой файл в корне — и файл из
# одних пробелов и переводов строки — не заслоняет написанный в `.claude/`.
#
# Заголовок ищется по началу: «## Что это за проект» — тоже «Что это».
# «Чего не трогать» — тот же раздел, что «Не трогать»: так говорит строка
# самой проверки. Невидимая метка в начале файла и неразрывный пробел в
# заголовке раздел не роняют (_jc_plain в md.sh).
# Заглушка вместо тела («TODO», прочерк) телом не считается. Подразделы —
# часть раздела: «## Не трогать», под ним «### Файлы» и список — не пусто
# (jc_section_deep_words в md.sh).
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/md.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"

if [ -d .claude ] && { [ ! -r .claude ] || [ ! -x .claude ]; }; then
  jc_bail "не могу заглянуть в папку .claude — проверь права на неё"
fi

# Написано ли в файле хоть что-то, кроме пробелов. Счёт, а не ранний выход:
# предикаты не пишут в stdout.
jc_written() { [ -f "$1" ] && grep -c '[^[:space:]]' "$1" >/dev/null 2>&1; }

FILE=CLAUDE.md
for candidate in CLAUDE.md .claude/CLAUDE.md; do
  if [ -e "$candidate" ] && [ ! -r "$candidate" ]; then
    jc_bail "не могу прочитать $candidate — проверь права на файл"
  fi
  if jc_written "$candidate"; then
    FILE=$candidate
    break
  fi
done

memory_written() { jc_written "$FILE"; }

jc_init "act2/03-memory"
jc_check memory_exists "Память проекта записана в файл CLAUDE.md в папке проекта" \
  "Попроси Claude записать память проекта в файл CLAUDE.md прямо в папке проекта." \
  memory_written
jc_check memory_what "Записано, что это за проект" \
  "Скажи Claude, что это за проект. Он запишет в раздел «Что это»." \
  jc_section_deep_words "$FILE" '[Чч]то[[:space:]]+это' 1
jc_check memory_open "Записано, как открыть проект" \
  "Скажи Claude, как ты открываешь проект. Он запишет в раздел «Как открыть»." \
  jc_section_deep_words "$FILE" '[Кк]ак[[:space:]]+открыть' 1
jc_check memory_keep "Записано, чего не трогать" \
  "Назови Claude хотя бы одно, чего в проекте не трогать. Он запишет в раздел «Не трогать»." \
  jc_section_deep_words "$FILE" '([Чч]его[[:space:]]+)?[Нн]е[[:space:]]+трогать' 1
jc_check memory_rules "Записано правило работы" \
  "Назови Claude правило работы. Например: сохраняй сам после важных изменений. Он запишет в раздел «Правила»." \
  jc_section_deep_words "$FILE" '[Пп]равил[ао]' 1
jc_finish
