#!/usr/bin/env bash
# Акт 2, квест 01: Claude показал план раньше правки, и человек его одобрил.
#
# В папке проекта этого не видно: режим плана файлов не оставляет. Действие
# записывает хук игровой сессии — это след (ADR-0020 в репозитории сайта), —
# а команда игры передаёт его сюда переменной JEDICODER_TRACE_PLAN_APPROVED=yes,
# тем же приёмом, каким квест «Папка» узнаёт, что папку назвал сам человек.
# Сохранение проверка не читает.
#
# Следа нет — честный провал с подсказкой повторить действие в игре, а не
# «не смог проверить»: проверить удалось, и ответ — «игра этого не видела».
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"

plan_approved() { [ "${JEDICODER_TRACE_PLAN_APPROVED:-}" = "yes" ]; }

jc_init "act2/01-plan"
jc_check plan_approved "Claude показал план, и ты его одобрил" \
  "Игра не видела одобренного плана. Набери /plan и своё дело. Прочитай план и нажми Enter на первой строке." \
  plan_approved
jc_finish
