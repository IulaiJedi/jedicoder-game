#!/usr/bin/env bash
# Акт 3, квест 03: проект сломан нарочно, слом зафиксирован коммитом.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

# Метка «слом:» — в ЗАГОЛОВКЕ коммита (%s), а не в любой строке сообщения:
# --grep матчит по любой строке, включая тело, и коммит с обычным
# заголовком, но со «слом:» где-то в теле, ложно прошёл бы эту проверку.
# grep -c дочитывает конвейер до конца (pipefail-safe) и даёт точное число
# совпадений — в отличие от grep -q, который выходит на первом же и рвёт
# трубу. Заодно урок: коммит есть точка отката, ломать не страшно.
has_break_commit() {
  [ "$(git log --format=%s 2>/dev/null | grep -c '^[Сс]лом:')" -ge 1 ]
}

jc_init "act3/03-break"
jc_check break_commit "Есть коммит слома с пометкой «слом:» в сообщении" \
  "Сломай проект нарочно и закоммить: сообщение начни со «слом: что сломал»" \
  has_break_commit
jc_finish
