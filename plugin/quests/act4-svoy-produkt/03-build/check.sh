#!/usr/bin/env bash
# Акт 4, квест 03: сборка по шагам.
#
# Claude делает план по одному шагу, человек смотрит после каждого и говорит
# «дальше», и рабочий шаг сохраняется. Проверка судит то, что от этого
# остаётся в папке проекта: сохранения (коммиты), сделанные после входа в
# акт, — не меньше трёх, и хотя бы одно меняет сам продукт, а не только
# заметки.
#
# Момент входа в акт отдаёт команда игры (JEDICODER_ACT_STARTED, секунды
# эпохи); сравнивается дата автора коммита (спека jedicoder.store#117).
# Коммиты первого вечера и шагов до входа в акт не считаются. Заметки — файлы
# markdown: `IDEA.md`, `HANDOFF.md`, `CLAUDE.md`, памятка. Служебное — всё,
# что в корне начинается с точки: `.gitignore`, `.env.example`, `.claude/`.
# Остальное — продукт: страница, стили, код бота.
#
# Строки идут по шагам: пока сохранений меньше трёх, вторая строка не
# печатается — одна подсказка на шаг.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"
command -v git >/dev/null 2>&1 || jc_bail "не найден git — поставь его и вернись"

STARTED="${JEDICODER_ACT_STARTED:-}"
case "$STARTED" in ''|*[!0-9]*) jc_bail "игра не знает, когда начался этот акт" ;; esac

NEED=3

# Свой репозиторий в самой папке проекта — как в квесте «Сохранение» Акта 1:
# папка внутри чужого репозитория иначе судилась бы по чужой истории.
repo_exists() { [ -e .git ] && git rev-parse --git-dir >/dev/null 2>&1; }

# Коммиты текущей ветки с датой автора не раньше входа в акт.
saves_after_entry() {
  repo_exists || { echo 0; return; }
  git log --format=%at HEAD 2>/dev/null \
    | awk -v started="$STARTED" '$1 >= started { n++ } END { print n + 0 }'
}

# Хотя бы один такой коммит меняет сам продукт: файл не markdown и не
# служебный. Служебное — всё, что начинается с точки в корне папки:
# `.gitignore`, `.env.example`, настройки `.claude/`. `@` в начале строки —
# граница коммита (имя файла с него не начинается: формат задаём мы); имена
# файлов идут без кавычек, кроме совсем странных, — у тех кавычка в начале
# и в конце, и точка и расширение ищутся рядом с ней.
code_saved() {
  repo_exists || return 1
  git -c core.quotePath=false log --format=@%at --name-only HEAD 2>/dev/null \
    | awk -v started="$STARTED" '
        /^@[0-9]+$/ { fresh = (substr($0, 2) + 0 >= started); next }
        $0 == "" { next }
        $0 ~ /^"?\./ { next }
        fresh && $0 !~ /\.([Mm][Dd]|[Mm][Aa][Rr][Kk][Dd][Oo][Ww][Nn])"?$/ { found = 1 }
        END { exit found ? 0 : 1 }
      '
}

COUNT=$(saves_after_entry)
case "$COUNT" in ''|*[!0-9]*) COUNT=0 ;; esac

enough_saves() { [ "$COUNT" -ge "$NEED" ]; }

jc_init "act4/03-build"
jc_check saves_after_entry "После входа в акт — не меньше трёх сохранений" \
  "Сохранений после входа в акт: ${COUNT} из ${NEED}. После каждого рабочего шага скажи Claude «дальше» — он сохранит шаг." \
  enough_saves
if enough_saves; then
  jc_check code_saved "В сохранениях есть сам продукт, а не только заметки" \
    "Пока сохранены только заметки. Попроси Claude сделать следующий шаг плана и сохранить его." \
    code_saved
fi
jc_finish
