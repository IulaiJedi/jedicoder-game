#!/usr/bin/env bash
# Акт 4, квест 01: что строим.
#
# Человек говорит своими словами, что строит и для кого, и добавляет «если
# что-то непонятно — задай вопросы». Claude спрашивает и записывает ответы в
# IDEA.md, в раздел «Продукт».
#
# Замер 2026-10-14 (docs/research/2026-10-14-act4-facts.md): Claude пишет
# раздел `## Продукт` в конец IDEA.md и подписывает строки жирным —
# «**Что это:**», «**Для кого:**», «**Что делает:**», «**Как я пойму, что
# готово:**», списком или абзацами; подзаголовков не ставит. Четыре строки он
# пишет, когда человек их назвал; без этого «как пойму, что готово» не
# появляется. Поэтому строки отчёта ищут смысл, а не разметку: слово в разделе,
# где бы оно ни стояло — в подписи, подзаголовке или тексте.
#
# Строки идут по шагам: раздела нет — одна строка и одна подсказка.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/md.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"

FILE=IDEA.md
SECTION='[Пп]родукт'

if [ -e "$FILE" ] && [ ! -r "$FILE" ]; then
  jc_bail "не могу прочитать IDEA.md — проверь права на файл"
fi

# «бот» — отдельным словом или после дефиса: «Telegram-бот», «боту». Слова
# вроде «работа» и «суббота» ботом не считаются.
KIND='[Сс]айт|[Сс]траниц|[Лл]ендинг|(^|[^[:alpha:]])[Бб]от'
# Подписи человек и Claude называют по-разному: «Для кого», «Кому», «Кто
# пользуется», «Пользователи»; «Что делает», «Что будет делать сайт»,
# «Что умеет»; «Как пойму, что готово», «Критерии готовности».
FOR_WHOM='[Дд]ля[[:space:]]+кого|[Кк]ому[[:space:]]*:|[Пп]ользу(ет|ют)ся|[Пп]ользоват'
DOES='[Чч]то[[:space:]]+([[:alpha:]]+[[:space:]]+){0,2}(делает|делать|умеет|уметь)'
# «готово», «готов», «готова», «готовность» — но не «готовым текстом».
DONE='[Гг]отов([оа]|[^[:alpha:]]|$)|[Гг]отовност'

section_written() { jc_section_deep_words "$FILE" "$SECTION" 10; }

jc_init "act4/01-what"
jc_check product_section "В IDEA.md есть раздел «Продукт»" \
  "Расскажи Claude, что строишь и для кого. Добавь: «Если тебе что-то непонятно или не хватает информации — задай вопросы. Потом запиши в IDEA.md раздел „Продукт“»." \
  section_written
if section_written; then
  jc_check product_kind "Записано, что это: сайт или бот" \
    "Скажи Claude, что это будет — сайт или Telegram-бот. Пусть допишет в раздел «Продукт» строку \`**Что это:**\`." \
    jc_section_deep_matches "$FILE" "$SECTION" "$KIND"
  jc_check product_for_whom "Записано, для кого" \
    "Скажи Claude, для кого твой продукт. Пусть допишет в раздел «Продукт» строку \`**Для кого:**\`." \
    jc_section_deep_matches "$FILE" "$SECTION" "$FOR_WHOM"
  jc_check product_does "Записано, что продукт делает" \
    "Скажи Claude, что продукт делает для человека. Пусть допишет в раздел «Продукт» строку \`**Что делает:**\`." \
    jc_section_deep_matches "$FILE" "$SECTION" "$DOES"
  jc_check product_done "Записано, как ты поймёшь, что готово" \
    "Скажи Claude, как ты поймёшь, что продукт готов. Пусть допишет в раздел «Продукт» строку \`**Как я пойму, что готово:**\`." \
    jc_section_deep_matches "$FILE" "$SECTION" "$DONE"
fi
jc_finish
