#!/usr/bin/env bash
# Акт 4, квест 02: план продукта одобрен — в этом акте.
#
# Как и квест «План» Акта 2, это след (ADR-0020 в репозитории сайта): режим
# плана файлов не оставляет, одобрение видит хук игровой сессии. Разница одна:
# план второго вечера квест четвёртого не закрывает. Пометка `in_act` у следа
# плана ставится один раз — во втором вечере, — поэтому здесь судится момент:
# пока квест открыт, хук пишет следу время последнего одобрения
# (JEDICODER_TRACE_PLAN_APPROVED_AT, секунды эпохи), а команда игры отдаёт
# момент входа в акт (JEDICODER_ACT_STARTED). Одобрение не раньше входа —
# квест закрыт.
#
# Следа или момента нет — честный провал с подсказкой повторить действие.
# Момента входа нет (сохранение правлено руками) — «не смог проверить».
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — скажи Claude, в какой папке лежит твой проект"

STARTED="${JEDICODER_ACT_STARTED:-}"
case "$STARTED" in ''|*[!0-9]*) jc_bail "игра не знает, когда начался этот акт" ;; esac

AT="${JEDICODER_TRACE_PLAN_APPROVED_AT:-}"
case "$AT" in ''|*[!0-9]*) AT="" ;; esac

plan_approved_in_act() {
  [ "${JEDICODER_TRACE_PLAN_APPROVED:-}" = "yes" ] || return 1
  [ -n "$AT" ] || return 1
  [ "$AT" -ge "$STARTED" ]
}

jc_init "act4/02-plan"
jc_check plan_approved "Claude показал план продукта, и ты его одобрил" \
  "Игра не видела плана в этом акте. Набери /plan и «Сделай то, что в разделе „Продукт“ в IDEA.md. Разбей на шаги». Прочитай план и нажми Enter на первой строке." \
  plan_approved_in_act
jc_finish
