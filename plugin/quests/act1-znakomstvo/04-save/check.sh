#!/usr/bin/env bash
# Акт 1, квест 04: первое сохранение сделано, и `.env` под защитой — git его
# не берёт, в сохранениях его нет, и строк, похожих на ключи, там нет тоже.
# О защите человек слышит, только если она не сошлась (jc_check_quiet ниже).
#
# Логика — из прежнего Акта 2 «Чертёж» (04-git-init и 05-env-guard; он на
# полке, shelf/act2-chertezh/), одним квестом: в режиме
# без вопросов точка возврата и защита секретов нужны в первый же вечер.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/secrets.sh"

[ -n "${JEDICODER_PROJECT_PATH:-}" ] \
  || jc_bail "папка проекта не названа — сначала закрой квест «Папка»"
command -v git >/dev/null 2>&1 || jc_bail "не найден git — поставь его и вернись"

# Репозиторий обязан начинаться в самой папке проекта. Папка, лежащая внутри
# чужого репозитория, отвечает git'у «да» и без своего `.git` — и сохранения
# падавана ушли бы в чужую историю. Поэтому своего `.git` требует каждая
# строка: без него судили бы внешний репозиторий, и чужой ключ в чужой
# истории читался бы как «твой ключ попал в сохранение». Строки-запреты без
# своего репозитория молчат — сохранений нет, и попасть в них нечему.
repo_exists() { [ -e .git ] && git rev-parse --git-dir >/dev/null 2>&1; }

jc_init "act1/04-save"
jc_check repo_exists "В папке проекта заведён git — он хранит сохранения" \
  "Попроси Claude завести git в папке проекта." \
  repo_exists
jc_check has_commit "Есть первое сохранение — коммит" \
  "Попроси Claude сохранить сделанное коммитом." \
  bash -c '[ -e .git ] && [ "$(git rev-list --count HEAD 2>/dev/null || echo 0)" -ge 1 ]'
# Три строки-сторожа тихие (jc_check_quiet): паролей у новичка в первый вечер
# нет, и про `.env` ему слышать рано (второй прогон 2026-10-08). Стерегут они
# по-прежнему, квест без них не закроется; человек видит строку, только когда
# она не сошлась, — и тогда подсказка спокойная. Первая молчит и без своего
# репозитория, как две другие: пока сохранять некуда, настраивать нечего.
jc_check_quiet env_ignored "Файл для паролей закрыт от сохранений" \
  "Это настройка на будущее: пароли в сохранения попадать не должны. Попроси Claude её доделать." \
  bash -c '[ ! -e .git ] || git check-ignore -q .env 2>/dev/null'
jc_check_quiet env_not_tracked "Файл .env в сохранения не попал" \
  "В файле .env держат пароли, и в сохранениях ему не место. Попроси Claude убрать его оттуда." \
  bash -c '[ ! -e .git ] || ! git ls-files 2>/dev/null | grep -qE "(^|/)\.env$"'
jc_check_quiet no_secrets_in_history "В сохранениях нет строк, похожих на пароль" \
  "В сохранение попала строка, похожая на пароль. Смени этот пароль. Убрать строку поможет Магистр: /jedicoder:magistr" \
  bash -c "[ ! -e .git ] || ! git log -p --all 2>/dev/null | grep -qE '$JC_SECRET_RE'"
jc_finish
