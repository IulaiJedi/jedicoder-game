#!/usr/bin/env bash
# Акт 1, квест 01: папку проекта назвал сам человек, она существует и это
# отдельная папка — не корень диска и не домашний каталог целиком.
#
# Судится папка, записанная в сохранении, а не та, откуда проверку
# запустили: движок передаёт её в JEDICODER_PROJECT_PATH и не ставит ключ
# вовсе, пока папки нет. Без записи защитный хук не стережёт `.env`,
# поэтому «не названа» — честный провал квеста, а не «не смог проверить».
#
# Записать папку может и приложение — на старте сессии, раньше первой
# команды. Тогда всё остальное сходится заранее, и квесту нечего было бы
# засчитывать (прогон новичком 2026-10-08). Поэтому отдельной строкой
# судится действие человека: JEDICODER_PROJECT_NAMED=yes движок ставит,
# только когда эту самую папку назвали командой `project path`.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

# Настоящий адрес папки — без ярлыков и точек по дороге. Пусто, если папки
# нет или в неё нельзя войти. Подоболочка: каталог самой проверки не меняется.
jc_real() { (cd -- "$1" 2>/dev/null && pwd -P); }

HOME_REAL=""
[ -n "${HOME:-}" ] && HOME_REAL=$(jc_real "$HOME")
[ -n "$HOME_REAL" ] \
  || jc_bail "не знаю, где твоя домашняя папка: переменная HOME пуста или ведёт в никуда"

RECORDED=${JEDICODER_PROJECT_PATH:-}
TARGET=""
[ -n "$RECORDED" ] && TARGET=$(jc_real "$RECORDED")

# Каждая строка судит своё и молчит о чужом: папка не названа — не сошлась
# одна строка, а не четыре.
path_recorded() { [ -n "$RECORDED" ]; }
path_named() { [ -z "$RECORDED" ] || [ "${JEDICODER_PROJECT_NAMED:-}" = "yes" ]; }
folder_exists() { [ -z "$RECORDED" ] || [ -n "$TARGET" ]; }
not_root() { [ "$TARGET" != "/" ]; }
not_home() {
  [ -n "$TARGET" ] || return 0
  [ "$TARGET" != "/" ] || return 0
  [ "$TARGET" != "$HOME_REAL" ] || return 1
  # Папка, внутри которой лежит домашняя (`/home`), — та же свалка, шире.
  case "$HOME_REAL/" in
    "$TARGET"/*) return 1 ;;
  esac
  return 0
}

jc_init "act1/01-folder"
jc_check path_recorded "Папка проекта записана" \
  "Скажи Claude, в какой папке будет твой проект." \
  path_recorded
jc_check path_named "Папку проекта назвал ты сам" \
  "Скажи Claude, в какой папке лежит твой проект." \
  path_named
jc_check folder_exists "Папка существует" \
  "Такой папки нет. Создай её или назови другую." \
  folder_exists
jc_check not_root "Это не корень диска" \
  "В корне диска лежит вся система. Заведи для проекта отдельную папку." \
  not_root
jc_check not_home "Это не домашняя папка целиком" \
  "В домашней папке лежит всё твоё. Заведи внутри неё папку для проекта." \
  not_home
jc_finish
