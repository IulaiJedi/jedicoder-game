#!/usr/bin/env bash
# Акт 2, квест 01: выбран стек, архитектура описана и это не заглушка.
set -uo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/../../_lib/emit.sh"

jc_init "act2/01-recipe"
jc_check arch_exists "ARCHITECTURE.md есть и непустой" \
  "Создай в корне проекта ARCHITECTURE.md" \
  test -s ARCHITECTURE.md
# Регистр складывается классами, а не `grep -i`: классу нужно только
# многобайтовое сопоставление, а `-i` нужно ещё и многобайтовое СЛОЖЕНИЕ
# регистра — слабое место BSD grep из macOS, заявленной целевой платформой.
# Ставка тут не край, а основной путь: подсказка велит писать «## Стек» с
# заглавной. Покрытие у классов то же: ловятся «Стек», «СТЕК», «стек», «СтЕк».
jc_check arch_has_stack "В ARCHITECTURE.md есть раздел про стек" \
  "Добавь заголовок «## Стек» и перечисли технологии с обоснованием" \
  grep -qE '^#+[[:space:]]*([Сс][Тт][Ее][Кк]|[Ss][Tt][Aa][Cc][Kk])' ARCHITECTURE.md
# Порог в байтах, а не в символах: кириллица в UTF-8 — два байта на символ,
# и метка «символов» обещала бы падавану вдвое больше, чем требует проверка.
jc_check arch_substantial "ARCHITECTURE.md не заглушка (от 400 байт)" \
  "Опиши подробнее: из каких частей состоит проект и почему выбран такой стек" \
  bash -c '[ "$(wc -c < ARCHITECTURE.md 2>/dev/null || echo 0)" -ge 400 ]'
jc_finish
