#: Маркер линтера контента: комментарий `<!-- lint:… -->` с начала строки,
#: бывает в несколько строк. Нужен файлу, а не читателю.
_LINT_MARKER = re.compile(r"^[ \t]*<!-- lint:.*?-->[ \t]*\n?", re.S | re.M)


def load_behavior(content_root):
    """Текст контракта из `behavior.md` — без маркеров линтера.

    Единственное место, где они срезаются: отсюда текст берут и команда
    `contract`, и раздел системного промпта, и инструмент игры, который
    показывает человеку первые строки ответа (#93). Обычные комментарии и
    сам файл не тронуты.
    """
    path = Path(content_root) / "behavior.md"
    _, body = parse(path.read_text(encoding="utf-8"))
    return _LINT_MARKER.sub("", body)


def resolve(passport):
    resolved = dict(DEFAULTS)
    for key, value in (passport or {}).items():
        if key in DEFAULTS:
            resolved[key] = value
    return resolved


#: Что контракт говорит модели о режиме разрешений. Режим называет сам
#: Claude Code данными хука (state.permission_mode); игра его не угадывает.
MODE_FREE = (
    "Режим Claude Code: без вопросов. Так сообщил сам Claude Code — "
    "падавану это можно сказать прямо."
)
MODE_OTHER = (
    "Режим Claude Code: другой, не «без вопросов». Claude Code сообщил "
    "режим `{}`: перед частью действий он спросит у падавана разрешения."
)
MODE_UNKNOWN = (
    "Режим Claude Code игре неизвестен. Не утверждай, в каком режиме "
    "работает падаван, и искать его на экране не проси."
)


def mode_directive(permission_mode):
    """Строка контракта о режиме — по тому, что вернул state.permission_mode."""
    if permission_mode is None:
        return MODE_UNKNOWN
    if permission_mode == st.PERMISSION_MODE_FREE:
        return MODE_FREE
    return MODE_OTHER.format(permission_mode)


def render(behavior_body, passport, mode=MODE_UNKNOWN):
    """`mode` — готовая строка о режиме (mode_directive): контракт состояния
    не читает, его читает вызывающий."""
    resolved = resolve(passport)
    lines = [behavior_body.strip(), "", SETTINGS_HEADER, ""]
    for knob in DIRECTIVE_ORDER:
        value = resolved[knob]
        directive = DIRECTIVES[knob].get(value)
        if directive is None:
            raise ContractError(
                "неизвестное значение ручки {}: {!r}".format(knob, value)
            )
        lines.append("- {}".format(directive))
    lines.append(
        "- Операционная система падавана: {}. Все команды давай под неё.".format(
            resolved["os"]
        )
    )
    lines.append("- Тип продукта: {}.".format(resolved["product_type"]))
    lines.append("- {}".format(mode))
    return "\n".join(lines) + "\n"


def section(text):
    """Контракт разделом системного промпта: заголовок, две пометки и сам текст.

    `text` — то, что вернул `render`. Слова раздела живут здесь, а не в
    модуле Лица: модуль слов игры не держит (ADR-0019).
    """
    return "\n".join(
        [SECTION_HEADER, "", SECTION_NOTE, "", SECTION_TOOLS, "", text]
    )


def stamp(section_text):
    """Отпечаток раздела: по нему Лицо видит, что текст сменился.

    Раздел зависит от паспорта и от режима разрешений. Отпечаток едет в
    снимке `face`, который модуль и так берёт на каждом ходу; сам раздел он
    перечитывает, только когда отпечаток стал другим.

    До модели доходит раздел, каким он был на первом запросе сессии: дальше
    системный промпт застывает (замер 2026-10-10, Claude Code 2.1.296).
    Перечитанное позже видит только рендер, который меряет место, — и
    следующая сессия.
    """
    return hashlib.sha256(section_text.encode("utf-8")).hexdigest()[:12]
